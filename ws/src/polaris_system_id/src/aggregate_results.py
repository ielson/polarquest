#!/usr/bin/env python3
"""Aggregate controller-comparison summary.json files.

Usage:
  rosrun polaris_system_id aggregate_results.py \
      --root $(rospack find polaris_system_id)/src/analysis/data/controller_comparison
"""

import argparse
import csv
import json
import math
from collections import defaultdict
from pathlib import Path
from statistics import mean, stdev
from typing import Dict, Iterable, List

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt


NOMINAL_METRICS = [
    "cte_rmse_m",
    "cte_p95_abs_m",
    "cte_max_abs_m",
    "heading_rmse_deg",
    "steering_rate_rms_deg_s",
    "compute_mean_ms",
    "compute_p95_ms",
    "compute_max_ms",
    "deadline_miss_percent",
    "completion_percent",
    "controller_failures",
]


def load_runs(root: Path) -> List[Dict]:
    runs: List[Dict] = []
    for path in sorted(root.rglob("summary.json")):
        with path.open() as stream:
            row = json.load(stream)
        row["summary_path"] = str(path)
        runs.append(row)
    if not runs:
        raise SystemExit(f"No summary.json files found below {root}")
    return runs


def write_csv(path: Path, rows: Iterable[Dict], fieldnames: List[str]) -> None:
    with path.open("w", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=fieldnames, extrasaction="ignore")
        writer.writeheader()
        writer.writerows(rows)


def finite(values: Iterable) -> List[float]:
    out = []
    for value in values:
        try:
            number = float(value)
        except (TypeError, ValueError):
            continue
        if math.isfinite(number):
            out.append(number)
    return out


def summarize_group(rows: List[Dict], metrics: List[str]) -> Dict:
    result = {
        "controller": rows[0]["controller"],
        "scenario": rows[0].get("scenario", "nominal"),
        "runs": len(rows),
    }
    for metric in metrics:
        values = finite(row.get(metric) for row in rows)
        result[f"{metric}_mean"] = mean(values) if values else float("nan")
        result[f"{metric}_std"] = stdev(values) if len(values) > 1 else 0.0
    return result


def latex_escape(text: str) -> str:
    return text.replace("_", r"\_")


def write_latex_nominal(path: Path, summaries: List[Dict]) -> None:
    lines = [
        "% Generated by aggregate_results.py",
        r"\begin{table*}[t]",
        r"\centering",
        r"\caption{Nominal closed-loop path-tracking comparison. Values are mean $\pm$ standard deviation across repeated runs.}",
        r"\label{tab:controller-comparison}",
        r"\begin{tabular}{lrrrrrr}",
        r"\hline",
        r"Controller & CTE RMSE [m] & $|$CTE$|_{95}$ [m] & Heading RMSE [$^\circ$] & $\dot{\delta}$ RMS [$^\circ$/s] & Solve p95 [ms] & Completion [\%] \\",
        r"\hline",
    ]
    for row in summaries:
        def pm(metric: str, digits: int) -> str:
            return f"{row[metric + '_mean']:.{digits}f} $\\pm$ {row[metric + '_std']:.{digits}f}"
        lines.append(
            f"{latex_escape(row['controller'])} & "
            f"{pm('cte_rmse_m', 3)} & "
            f"{pm('cte_p95_abs_m', 3)} & "
            f"{pm('heading_rmse_deg', 2)} & "
            f"{pm('steering_rate_rms_deg_s', 2)} & "
            f"{pm('compute_p95_ms', 2)} & "
            f"{pm('completion_percent', 1)} \\\\" 
        )
    lines.extend([r"\hline", r"\end{tabular}", r"\end{table*}"])
    path.write_text("\n".join(lines) + "\n")


def write_latex_robustness(path: Path, summaries: List[Dict]) -> None:
    lines = [
        "% Generated by aggregate_results.py",
        r"\begin{table}[t]",
        r"\centering",
        r"\caption{Robustness to initial-pose perturbations.}",
        r"\label{tab:robustness}",
        r"\begin{tabular}{llrr}",
        r"\hline",
        r"Controller & Scenario & CTE RMSE [m] & Completion [\%] \\",
        r"\hline",
    ]
    for row in summaries:
        lines.append(
            f"{latex_escape(row['controller'])} & {latex_escape(row['scenario'])} & "
            f"{row['cte_rmse_m_mean']:.3f} & {row['completion_percent_mean']:.1f} \\\\" 
        )
    lines.extend([r"\hline", r"\end{tabular}", r"\end{table}"])
    path.write_text("\n".join(lines) + "\n")


def save_nominal_plot(path: Path, summaries: List[Dict]) -> None:
    labels = [row["controller"] for row in summaries]
    values = [row["cte_rmse_m_mean"] for row in summaries]
    errors = [row["cte_rmse_m_std"] for row in summaries]
    plt.figure(figsize=(7, 4))
    plt.bar(labels, values, yerr=errors, capsize=4)
    plt.ylabel("CTE RMSE [m]")
    plt.xticks(rotation=20, ha="right")
    plt.tight_layout()
    plt.savefig(path, dpi=180)
    plt.close()


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", required=True, type=Path)
    parser.add_argument("--out", type=Path, default=None)
    args = parser.parse_args()

    root = args.root.resolve()
    out = (args.out or (root / "aggregated")).resolve()
    out.mkdir(parents=True, exist_ok=True)
    runs = load_runs(root)

    all_fields = sorted({key for row in runs for key in row.keys()})
    write_csv(out / "all_runs.csv", runs, all_fields)

    grouped = defaultdict(list)
    for row in runs:
        grouped[(row["controller"], row.get("scenario", "nominal"))].append(row)

    summaries = [
        summarize_group(rows, NOMINAL_METRICS)
        for _, rows in sorted(grouped.items())
    ]
    summary_fields = list(summaries[0].keys())
    write_csv(out / "scenario_summary.csv", summaries, summary_fields)

    nominal = [row for row in summaries if row["scenario"] == "nominal"]
    robustness = [row for row in summaries if row["scenario"] != "nominal"]
    write_csv(out / "nominal_summary.csv", nominal, summary_fields)
    if robustness:
        write_csv(out / "robustness_summary.csv", robustness, summary_fields)

    write_latex_nominal(out / "comparison_table.tex", nominal)
    if robustness:
        write_latex_robustness(out / "robustness_table.tex", robustness)
    save_nominal_plot(out / "cte_rmse_comparison.png", nominal)

    print(f"Aggregated {len(runs)} runs into {out}")


if __name__ == "__main__":
    main()
